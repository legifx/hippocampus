//! Generates the synthetic corpus the benchmarks measure against.
//!
//! The corpus is a **generator checked into the repository, not data**. Committing a hundred
//! thousand files would be absurd, and committing a tarball would make the corpus opaque. From
//! a seed, this produces a byte-identical tree on any machine at any time, which is the only
//! way a latency number from one session means anything in the next.
//!
//! The shape is deliberately realistic rather than uniform:
//!
//! - a heavy tail of directory sizes — most directories are small, a few hold thousands
//! - a mix of extensions, most of which are never worth extracting
//! - dependency and build trees that must be skipped, which is where a naive walker dies
//! - credential-shaped files, so the deny-list is exercised by every benchmark run rather
//!   than only by its own unit tests
//! - German and English content, mixed within files as well as across them

mod rng;
mod words;

use clap::Parser;
use rng::Rng;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

#[derive(Parser, Debug)]
#[command(name = "corpus-gen", about = "Generate the reproducible benchmark corpus")]
struct Args {
    /// Where to build the corpus. Refuses to write into a non-empty directory unless --force.
    #[arg(long)]
    out: PathBuf,

    /// Approximate number of files. The tree shape makes the exact count vary slightly.
    #[arg(long, default_value_t = 100_000)]
    files: usize,

    /// Change this and you have a different corpus. Do not change it casually.
    #[arg(long, default_value_t = 20260817)]
    seed: u64,

    /// Write real content into text and code files. Off by default: the M1 benchmarks only
    /// index metadata, and empty files make a 100k-file corpus fit in a fraction of the space.
    #[arg(long)]
    with_content: bool,

    /// Overwrite an existing corpus.
    #[arg(long)]
    force: bool,
}

fn main() -> std::io::Result<()> {
    let args = Args::parse();

    if args.out.exists() {
        let non_empty = fs::read_dir(&args.out)?.next().is_some();
        if non_empty && !args.force {
            eprintln!(
                "{} is not empty. Pass --force to replace it.",
                args.out.display()
            );
            std::process::exit(1);
        }
        if non_empty {
            fs::remove_dir_all(&args.out)?;
        }
    }
    fs::create_dir_all(&args.out)?;

    let mut rng = Rng::new(args.seed);
    let mut stats = Stats::default();

    generate_sensitive_files(&args.out, &mut stats)?;

    // Files are distributed across the top-level areas by weight, so the corpus has a few
    // large zones and several small ones rather than an unrealistic even split.
    let weights: &[(&str, usize)] = &[
        ("Documents", 22),
        ("Projects", 40),
        ("Pictures", 18),
        ("Downloads", 8),
        ("Music", 4),
        ("Videos", 2),
        ("Archive", 5),
        ("Notes", 1),
    ];
    let total_weight: usize = weights.iter().map(|(_, w)| w).sum();

    for (area, weight) in weights {
        let quota = args.files * weight / total_weight;
        let root = args.out.join(area);
        fs::create_dir_all(&root)?;

        match *area {
            "Projects" => generate_projects(&root, quota, &mut rng, args.with_content, &mut stats)?,
            "Pictures" => generate_media(&root, quota, words::IMAGE_EXTENSIONS, &mut rng, &mut stats)?,
            "Music" | "Videos" => {
                generate_media(&root, quota, words::MEDIA_EXTENSIONS, &mut rng, &mut stats)?
            }
            "Downloads" => generate_downloads(&root, quota, &mut rng, args.with_content, &mut stats)?,
            _ => generate_documents(&root, quota, &mut rng, args.with_content, &mut stats)?,
        }
    }

    println!(
        "corpus at {}\n  {} files in {} directories\n  {} skippable (dependency and build trees)\n  {} sensitive (must never be indexed)\n  seed {}",
        args.out.display(),
        stats.files,
        stats.dirs,
        stats.skippable,
        stats.sensitive,
        args.seed
    );

    Ok(())
}

#[derive(Default)]
struct Stats {
    files: usize,
    dirs: usize,
    skippable: usize,
    sensitive: usize,
}

/// Credential-shaped files, so every benchmark run also proves the deny-list holds.
///
/// Their contents are obviously fake. A generator that wrote realistic-looking keys would be a
/// liability the first time someone tarred up their corpus directory.
fn generate_sensitive_files(root: &Path, stats: &mut Stats) -> std::io::Result<()> {
    let entries: &[(&str, &str)] = &[
        (".ssh/id_ed25519", "NOT-A-REAL-KEY generated by corpus-gen\n"),
        (".ssh/id_rsa", "NOT-A-REAL-KEY generated by corpus-gen\n"),
        (".ssh/known_hosts", "NOT-REAL generated by corpus-gen\n"),
        (".aws/credentials", "NOT-REAL generated by corpus-gen\n"),
        (".gnupg/secring.gpg", "NOT-REAL generated by corpus-gen\n"),
        ("Projects/aurora/.env", "NOT_A_REAL_TOKEN=generated-by-corpus-gen\n"),
        ("Projects/aurora/.env.production", "NOT_A_REAL_TOKEN=generated\n"),
        ("Documents/vault.kdbx", "NOT-REAL generated by corpus-gen\n"),
        ("Documents/server.pem", "NOT-A-REAL-CERT generated by corpus-gen\n"),
    ];

    for (relative, contents) in entries {
        let path = root.join(relative);
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(&path, contents)?;
        stats.sensitive += 1;
    }
    Ok(())
}

fn generate_projects(
    root: &Path,
    quota: usize,
    rng: &mut Rng,
    with_content: bool,
    stats: &mut Stats,
) -> std::io::Result<()> {
    let mut remaining = quota;
    let mut index = 0usize;

    while remaining > 0 {
        let name = format!("{}-{}", rng.pick(words::PROJECT_NAMES), index);
        index += 1;
        let project = root.join(&name);
        fs::create_dir_all(&project)?;
        stats.dirs += 1;

        // Source tree.
        let source_files = rng.range(5, 60).min(remaining);
        for dir in words::CODE_DIRS {
            if !rng.chance(70) {
                continue;
            }
            let sub = project.join(dir);
            fs::create_dir_all(&sub)?;
            stats.dirs += 1;

            let here = (source_files / 3).max(1).min(remaining);
            for _ in 0..here {
                let file = sub.join(format!(
                    "{}_{}.{}",
                    rng.pick(words::EN_NOUNS),
                    rng.below(10_000),
                    rng.pick(words::CODE_EXTENSIONS)
                ));
                write_file(&file, with_content, rng)?;
                stats.files += 1;
                remaining -= 1;
                if remaining == 0 {
                    return Ok(());
                }
            }
        }

        // The trees a walker must skip. Their contents are what makes a naive indexer
        // spend an hour on a home directory, so the corpus has to contain them.
        for noisy in ["node_modules", "target", ".git"] {
            if !rng.chance(60) {
                continue;
            }
            let dir = project.join(noisy).join("deep").join("nested");
            fs::create_dir_all(&dir)?;
            stats.dirs += 3;
            for i in 0..rng.range(20, 200) {
                fs::write(dir.join(format!("chunk_{i}.bin")), b"")?;
                stats.skippable += 1;
            }
        }
    }
    Ok(())
}

fn generate_documents(
    root: &Path,
    quota: usize,
    rng: &mut Rng,
    with_content: bool,
    stats: &mut Stats,
) -> std::io::Result<()> {
    let mut remaining = quota;
    let mut year = 2019;

    while remaining > 0 {
        // A heavy tail: most directories are small, a few are enormous. A uniform tree would
        // hide exactly the pathological case the 10 000-entry budget exists for.
        let size = if rng.chance(5) {
            rng.range(800, 3000)
        } else {
            rng.range(3, 40)
        }
        .min(remaining);

        let dir = root.join(format!("{year}")).join(format!(
            "{}-{}",
            rng.pick(words::EN_NOUNS),
            rng.below(1000)
        ));
        fs::create_dir_all(&dir)?;
        stats.dirs += 2;
        year = if year >= 2026 { 2019 } else { year + 1 };

        for _ in 0..size {
            let (noun, ext) = if rng.chance(50) {
                (rng.pick(words::DE_NOUNS), rng.pick(words::TEXT_EXTENSIONS))
            } else {
                (rng.pick(words::EN_NOUNS), rng.pick(words::DOC_EXTENSIONS))
            };
            let file = dir.join(format!(
                "{}-{}-{}.{}",
                rng.pick(words::ADJECTIVES),
                noun,
                rng.below(100_000),
                ext
            ));
            write_file(&file, with_content, rng)?;
            stats.files += 1;
            remaining -= 1;
            if remaining == 0 {
                break;
            }
        }
    }
    Ok(())
}

fn generate_media(
    root: &Path,
    quota: usize,
    extensions: &[&str],
    rng: &mut Rng,
    stats: &mut Stats,
) -> std::io::Result<()> {
    let mut remaining = quota;
    let mut album = 0usize;

    while remaining > 0 {
        let dir = root.join(format!(
            "{}-{album}",
            rng.pick(words::PROJECT_NAMES)
        ));
        fs::create_dir_all(&dir)?;
        stats.dirs += 1;
        album += 1;

        let size = rng.range(20, 400).min(remaining);
        for i in 0..size {
            // Camera-style names: long, near-identical, and genuinely hard to tell apart.
            // This is precisely the case the preview pane exists for.
            let file = dir.join(format!(
                "IMG_{:04}{:02}{:02}_{:06}.{}",
                2019 + (i % 7),
                1 + (i % 12),
                1 + (i % 28),
                rng.below(999_999),
                rng.pick(extensions)
            ));
            fs::write(&file, b"")?;
            stats.files += 1;
            remaining -= 1;
            if remaining == 0 {
                break;
            }
        }
    }
    Ok(())
}

fn generate_downloads(
    root: &Path,
    quota: usize,
    rng: &mut Rng,
    with_content: bool,
    stats: &mut Stats,
) -> std::io::Result<()> {
    // One flat directory holding everything, which is what a real Downloads folder looks like
    // and a good test of opening a large directory quickly.
    stats.dirs += 1;
    for _ in 0..quota {
        let ext = if rng.chance(40) {
            rng.pick(words::BINARY_EXTENSIONS)
        } else if rng.chance(50) {
            rng.pick(words::DOC_EXTENSIONS)
        } else {
            rng.pick(words::TEXT_EXTENSIONS)
        };
        let file = root.join(format!(
            "{}_{}_{}.{}",
            rng.pick(words::EN_NOUNS),
            rng.pick(words::DE_NOUNS),
            rng.below(1_000_000),
            ext
        ));
        write_file(&file, with_content, rng)?;
        stats.files += 1;
    }
    Ok(())
}

fn write_file(path: &Path, with_content: bool, rng: &mut Rng) -> std::io::Result<()> {
    if !with_content {
        return fs::write(path, b"");
    }

    let mut file = fs::File::create(path)?;
    for _ in 0..rng.range(3, 40) {
        writeln!(file, "{}", rng.pick(words::SENTENCES))?;
    }
    Ok(())
}
